export function isWeakPin(digits: readonly number[]): boolean {
  if (digits.length !== 6 || digits.some((d) => !Number.isInteger(d) || d < 0 || d > 9)) return true;
  const s = digits.join('');
  if (/^(\d)\1{5}$/.test(s)) return true; // all same
  const diffs = digits.slice(1).map((d, i) => d - digits[i]!);
  if (diffs.every((x) => x === 1) || diffs.every((x) => x === -1)) return true; // ascending / descending runs
  if (/^(\d\d)\1\1$/.test(s) || /^(\d\d\d)\1$/.test(s)) return true; // repeating pairs / triples
  return TOP_COMMON.has(s);
}

